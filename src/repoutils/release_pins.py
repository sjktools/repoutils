"""The pins file that ``github-releases bump`` writes, which pins one GitHub
repository's release assets by digest, kept apart from the command for length.

The project that pins the assets reads the file at runtime. It's TOML, like::

    repo = "owner/name"
    current = "v1.2.0"

    [releases."v1.2.0"]
    "tool-linux-x64.vsix" = "sha256:<64 hex digits>"

    [releases."v1.1.0"]
    "tool-linux-x64.vsix" = "sha256:<64 hex digits>"

``current`` is the tag in use, and ``releases`` keeps every tag the file has
pinned, newest first, so a project can go back to an earlier one. tomllib
can't write TOML, so ``render`` writes the whole file in this one layout.
Stdlib-only, like every repoutils module."""

import re
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

from repoutils.config import toml_key, toml_string

HEADER = (
    "# Generated by `repoutils github-releases bump`, which rewrites this whole file,\n"
    "# so a comment or change of layout here doesn't last.\n"
)
# The form the releases API gives an asset's digest in.
DIGEST_RE = re.compile(r"sha256:[0-9a-f]{64}")


@dataclass
class Pins:
    """What a pins file holds: the repository, the tag in use, and each
    pinned tag's assets, as asset name to digest, newest tag first."""

    repo: str
    current: str | None = None
    releases: dict[str, dict[str, str]] = field(default_factory=dict[str, dict[str, str]])


def read(path: Path, repo: str) -> Pins:
    """The pins in the file at path, which must pin repo's releases, or no
    pins if there's no file yet. Raises ValueError, naming path, if the file
    isn't a pins file."""
    if not path.exists():
        return Pins(repo)
    try:
        with path.open("rb") as f:
            data = tomllib.load(f)
    except tomllib.TOMLDecodeError as error:
        raise ValueError(f"{path}: {error}") from error
    except UnicodeDecodeError as error:
        raise ValueError(f"{path}: not valid UTF-8") from error
    unknown = sorted(set(data) - {"repo", "current", "releases"})
    if unknown:
        raise ValueError(f"{path} has unknown key(s): {', '.join(unknown)}")
    if data.get("repo") != repo:
        raise ValueError(f"{path} pins the releases of {data.get('repo')!r}, not {repo!r}")
    current = data.get("current")
    releases = data.get("releases", {})
    if not isinstance(releases, dict):
        raise ValueError(f"{path}: releases must be a table")
    pins = Pins(repo)
    for tag, assets in releases.items():
        if not isinstance(assets, dict) or not assets:
            raise ValueError(f"{path}: releases.{toml_key(tag)} must be a table of asset names and digests")
        for name, digest in assets.items():
            if not isinstance(digest, str) or not DIGEST_RE.fullmatch(digest):
                raise ValueError(
                    f"{path}: the digest of {name} in releases.{toml_key(tag)} must be sha256: and 64 hex digits"
                )
        pins.releases[tag] = dict(assets)
    if current is not None and (not isinstance(current, str) or current not in pins.releases):
        raise ValueError(f"{path}: current must be the tag of one of its releases")
    if current is None and pins.releases:
        raise ValueError(f"{path}: current must say which of its releases is in use")
    pins.current = current
    return pins


def add(pins: Pins, tag: str, assets: dict[str, str]) -> None:
    """Make tag, with assets, the current release, keeping the earlier ones after it."""
    pins.releases = {tag: dict(sorted(assets.items())), **{t: a for t, a in pins.releases.items() if t != tag}}
    pins.current = tag


def render(pins: Pins) -> str:
    """The pins file's text, once it pins a release."""
    if pins.current is None:
        raise ValueError("A pins file needs a current release")
    lines = [HEADER, f"repo = {toml_string(pins.repo)}", f"current = {toml_string(pins.current)}"]
    for tag, assets in pins.releases.items():
        lines += ["", f"[releases.{toml_key(tag)}]"]
        lines += [f"{toml_key(name)} = {toml_string(digest)}" for name, digest in assets.items()]
    return "\n".join(lines) + "\n"
